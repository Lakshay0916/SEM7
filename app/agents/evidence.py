"""The evidence package the agents work from - built deterministically from the real run.

Agents may only reason over these facts (failing tests, tracebacks, the developer's diff,
the current and baseline code, earlier attempts). Nothing here is generated by a model.
"""

from __future__ import annotations

from app.git.repo import GitRepo
from app.healing.code_utils import function_source
from app.healing.strategy import RepairContext

MAX_PATCH = 6000
MAX_FILE = 8000
MAX_TRACE = 1500


def _clip(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[:limit] + f"\n… [truncated, {len(text) - limit} more chars]"


def source_files(ctx: RepairContext) -> list[str]:
    return [f.path for f in ctx.failure.diff.files
            if f.path.endswith(".py") and not (f.is_test or f.is_config or f.is_dependency)]


def build_evidence(ctx: RepairContext) -> str:
    repo = GitRepo(ctx.repo_dir)
    diff = ctx.failure.diff
    out = [f"# Evidence for repair attempt {ctx.attempt}",
           f"Commit {ctx.failure.commit_sha[:10]} on branch `{ctx.failure.branch}`; healthy baseline is "
           f"`{ctx.base_branch}` ({diff.base_sha[:10]}).",
           f"Latest real test run: {ctx.current_report.status.value} - {ctx.current_report.tests_passed} passed, "
           f"{ctx.current_report.tests_failed} failed, {ctx.current_report.tests_errored} errors."]

    out.append("\n## Failing tests")
    for f in ctx.current_report.failures:
        out.append(f"### {f.node_id} ({f.outcome})\nMessage: {f.message.strip() or '-'}\n"
                   f"Traceback:\n```\n{_clip(f.traceback.strip(), MAX_TRACE)}\n```")
        path, _, name = f.node_id.partition("::")
        test_file = ctx.repo_dir / path
        if name and test_file.is_file():
            src = function_source(test_file.read_text(encoding="utf-8"), name.split("[")[0])
            if src:
                out.append(f"Test source:\n```python\n{src}```")

    out.append("\n## Developer's change (unified diff vs baseline)")
    for f in diff.files:
        out.append(f"- {f.path} ({f.change_type}, +{f.additions}/-{f.deletions}); functions changed: "
                   f"{', '.join(f.functions_changed) or '-'}")
    out.append(f"```diff\n{_clip(diff.patch, MAX_PATCH)}\n```")

    for path in source_files(ctx):
        current = ctx.repo_dir / path
        if current.is_file():
            out.append(f"\n## Current content of `{path}` (this is what a fix will edit)\n"
                       f"```python\n{_clip(current.read_text(encoding='utf-8'), MAX_FILE)}\n```")
        changed = next((f.functions_changed for f in diff.files if f.path == path), [])
        try:
            base_src = repo.show_file(diff.base_sha, path)
        except Exception:
            base_src = ""
        for fn in changed:
            base_fn = function_source(base_src, fn) if base_src else None
            if base_fn:
                out.append(f"Baseline version of `{fn}()` before the commit:\n```python\n{base_fn}```")

    if ctx.previous_plans:
        out.append("\n## Earlier repair attempts (already applied, not sufficient)")
        for p in ctx.previous_plans:
            out.append(f"- Attempt {p.attempt} ({p.strategy}/{p.level}): {p.summary}")
        for r in ctx.reflections:
            out.append(f"- Reflection after attempt {r.attempt}: {r.summary} Still failing: "
                       f"{', '.join(r.still_failing) or '-'}; regressions: {', '.join(r.regressions) or '-'}")
    return "\n".join(out)
